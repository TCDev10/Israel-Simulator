import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.*;

/**
 * gaza_strip is a large jigsaw ruined district (about 10x the old single 32x32 template),
 * generated by scripts/worldgen/gen_gaza_strip.py.
 */
class GazaStripStructureTest {

    private static final Gson GSON = new Gson();
    private static final String NS = "israel_simulator:";
    private static final List<String> POOLS = List.of("gaza_strip", "gaza/streets", "gaza/terminators", "gaza/buildings");
    private static final Set<String> ALLOWED = Set.of(
            "minecraft:air", "minecraft:jigsaw", "minecraft:cobblestone", "minecraft:stone",
            "minecraft:cobbled_deepslate", "minecraft:gravel", "minecraft:cracked_stone_bricks",
            "minecraft:cobbled_deepslate_wall", "minecraft:cobblestone_wall", "minecraft:cobblestone_slab",
            "minecraft:cobbled_deepslate_slab", "minecraft:stone_slab", "minecraft:cobblestone_stairs",
            "minecraft:iron_bars", "minecraft:ladder");

    @Test
    @DisplayName("gaza_strip is a big jigsaw on the Mediterranean coast starting at gaza/square")
    void structureJson() throws Exception {
        JsonObject s = readJson("data/israel_simulator/worldgen/structure/gaza_strip.json");
        assertEquals("minecraft:jigsaw", s.get("type").getAsString());
        assertTrue(s.get("size").getAsInt() >= 6, "jigsaw depth too small for a 10x district");
        int maxDist = s.get("max_distance_from_center").getAsInt();
        assertTrue(maxDist >= 56 && maxDist <= 128, "max_distance_from_center " + maxDist);
        assertEquals("none", s.get("terrain_adaptation").getAsString(), "no beard: no coastal sand pulled under the ruins");
        JsonArray biomes = s.getAsJsonArray("biomes");
        assertEquals(1, biomes.size());
        assertEquals("israel_simulator:mediterranean_coast", biomes.get(0).getAsString());
        assertEquals(NS + "gaza/square", firstLocation("gaza_strip"));
        assertNull(getClass().getClassLoader().getResource("data/israel_simulator/structure/gaza_strip.nbt"),
                "the old single-piece template is replaced by the jigsaw");
    }

    @Test
    @DisplayName("Pools resolve, use the Gaza processors and offer many random variants")
    void poolsResolve() throws Exception {
        int buildings = 0, streets = 0;
        for (String pool : POOLS) {
            JsonObject p = readJson(poolPath(pool));
            String fallback = p.get("fallback").getAsString();
            assertTrue(fallback.equals("minecraft:empty") || POOLS.contains(fallback.substring(NS.length())), fallback);
            for (var el : p.getAsJsonArray("elements")) {
                JsonObject e = el.getAsJsonObject().getAsJsonObject("element");
                String loc = e.get("location").getAsString();
                assertTrue(loc.startsWith(NS + "gaza/"), loc);
                String proc = e.get("processors").getAsString();
                assertTrue(proc.startsWith(NS + "gaza_"), loc + " must use a gaza processor list: " + proc);
                assertNotNull(getClass().getClassLoader().getResource(
                        "data/israel_simulator/worldgen/processor_list/" + proc.substring(NS.length()) + ".json"), proc);
                boolean street = pool.endsWith("/streets") || pool.endsWith("/terminators");
                assertEquals(street ? "terrain_matching" : "rigid", e.get("projection").getAsString(), loc);
                if (pool.equals("gaza/buildings")) buildings++;
                if (pool.equals("gaza/streets")) streets++;
                assertNotNull(Template.load(readGzip(nbtPath(loc.substring(NS.length())))));
            }
        }
        assertTrue(buildings >= 20, "expected many building variants, got " + buildings);
        assertTrue(streets >= 8, "expected many street variants, got " + streets);
    }

    @Test
    @DisplayName("Every piece keeps the old stone palette (no sand, no sandstone) and buildings have one entrance")
    void paletteAndWiring() throws Exception {
        for (String pool : POOLS) {
            for (var el : readJson(poolPath(pool)).getAsJsonArray("elements")) {
                String piece = el.getAsJsonObject().getAsJsonObject("element").get("location").getAsString()
                        .substring(NS.length());
                Template t = Template.load(readGzip(nbtPath(piece)));
                for (Block b : t.blocks) {
                    assertTrue(ALLOWED.contains(b.name), piece + " uses off-palette block " + b.name);
                    if (b.name.equals("minecraft:jigsaw")) {
                        String target = (String) b.nbt.get("pool");
                        assertTrue(target.equals("minecraft:empty") || POOLS.contains(target.substring(NS.length())),
                                piece + " jigsaw targets unknown pool " + target);
                    }
                }
                if (pool.equals("gaza/buildings")) {
                    List<Block> js = t.blocks.stream().filter(b -> b.name.equals("minecraft:jigsaw")).toList();
                    assertEquals(1, js.size(), piece + " must have exactly one entrance");
                    assertEquals("minecraft:building_entrance", js.get(0).nbt.get("name"));
                    assertEquals("north_up", js.get(0).props.get("orientation"));
                    assertEquals(0, js.get(0).z);
                }
            }
        }
        Template start = Template.load(readGzip(nbtPath("gaza/square")));
        assertTrue(start.blocks.stream().anyMatch(b -> b.name.equals("minecraft:cobbled_deepslate")));
        long towers = readJson(poolPath("gaza/buildings")).getAsJsonArray("elements").asList().stream()
                .filter(e -> e.getAsJsonObject().getAsJsonObject("element").get("location").getAsString().contains("watchtower"))
                .count();
        assertTrue(towers >= 4, "watchtowers of several heights expected");
        Template tall = Template.load(readGzip(nbtPath("gaza/watchtower_0")));
        assertTrue(tall.blocks.stream().filter(b -> b.name.equals("minecraft:ladder")).count() >= 12, "tower ladder");
    }

    private String firstLocation(String pool) throws Exception {
        return readJson(poolPath(pool)).getAsJsonArray("elements").get(0).getAsJsonObject()
                .getAsJsonObject("element").get("location").getAsString();
    }

    private static String poolPath(String pool) {
        return "data/israel_simulator/worldgen/template_pool/" + pool + ".json";
    }

    private static String nbtPath(String piece) {
        return "data/israel_simulator/structure/" + piece + ".nbt";
    }

    private JsonObject readJson(String path) throws Exception {
        InputStream in = getClass().getClassLoader().getResourceAsStream(path);
        assertNotNull(in, "Missing " + path);
        return GSON.fromJson(new InputStreamReader(in, StandardCharsets.UTF_8), JsonObject.class);
    }

    private byte[] readGzip(String path) throws Exception {
        InputStream in = getClass().getClassLoader().getResourceAsStream(path);
        assertNotNull(in, "Missing NBT: " + path);
        try (GZIPInputStream gz = new GZIPInputStream(in)) {
            return gz.readAllBytes();
        }
    }

    private record Block(String name, Map<String, Object> props, int x, int y, int z, Map<String, Object> nbt) {}

    private record Template(List<Block> blocks) {
        @SuppressWarnings("unchecked")
        static Template load(byte[] raw) throws IOException {
            DataInputStream in = new DataInputStream(new ByteArrayInputStream(raw));
            assertEquals(10, in.readByte());
            readString(in);
            Map<String, Object> root = readCompound(in);
            List<Map<String, Object>> palette = (List<Map<String, Object>>) root.get("palette");
            List<Block> out = new ArrayList<>();
            for (Map<String, Object> b : (List<Map<String, Object>>) root.get("blocks")) {
                List<Integer> pos = (List<Integer>) b.get("pos");
                Map<String, Object> state = palette.get(((Number) b.get("state")).intValue());
                Map<String, Object> props = (Map<String, Object>) state.getOrDefault("Properties", Map.of());
                out.add(new Block((String) state.get("Name"), props, pos.get(0), pos.get(1), pos.get(2),
                        (Map<String, Object>) b.get("nbt")));
            }
            return new Template(out);
        }
    }

    private static Map<String, Object> readCompound(DataInputStream in) throws IOException {
        Map<String, Object> map = new HashMap<>();
        while (true) {
            byte type = in.readByte();
            if (type == 0) {
                return map;
            }
            String name = readString(in);
            map.put(name, readPayload(in, type));
        }
    }

    private static Object readPayload(DataInputStream in, byte type) throws IOException {
        return switch (type) {
            case 1 -> in.readByte();
            case 2 -> in.readShort();
            case 3 -> in.readInt();
            case 4 -> in.readLong();
            case 5 -> in.readFloat();
            case 6 -> in.readDouble();
            case 7 -> {
                int len = in.readInt();
                in.skipBytes(len);
                yield new byte[0];
            }
            case 8 -> readString(in);
            case 9 -> readList(in);
            case 10 -> readCompound(in);
            case 11 -> {
                int len = in.readInt();
                for (int i = 0; i < len; i++) {
                    in.readInt();
                }
                yield new int[0];
            }
            case 12 -> {
                int len = in.readInt();
                for (int i = 0; i < len; i++) {
                    in.readLong();
                }
                yield new long[0];
            }
            default -> throw new IOException("Unsupported NBT type " + type);
        };
    }

    private static Object readList(DataInputStream in) throws IOException {
        byte elemType = in.readByte();
        int len = in.readInt();
        List<Object> list = new ArrayList<>(len);
        for (int i = 0; i < len; i++) {
            list.add(readPayload(in, elemType));
        }
        if (elemType == 3) {
            List<Integer> ints = new ArrayList<>(len);
            for (Object o : list) {
                ints.add(((Number) o).intValue());
            }
            return ints;
        }
        if (elemType == 10) {
            @SuppressWarnings("unchecked")
            List<Map<String, Object>> compounds = (List<Map<String, Object>>) (List<?>) list;
            return compounds;
        }
        return list;
    }

    private static String readString(DataInputStream in) throws IOException {
        int len = in.readUnsignedShort();
        return new String(in.readNBytes(len), StandardCharsets.UTF_8);
    }
}

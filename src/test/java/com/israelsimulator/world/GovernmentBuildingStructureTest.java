package com.israelsimulator.world;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import java.io.ByteArrayInputStream;
import java.io.DataInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.zip.GZIPInputStream;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.*;

/**
 * desert_ruins is a jigsaw ancient settlement (Qumran-style) in the Judean desert, generated by
 * scripts/worldgen/gen_desert_ruins.py.
 */
/**
 * government_building has two variants (Knesset-style parliament, ministry tower), generated by
 * scripts/worldgen/gen_government_building.py.
 */
class GovernmentBuildingStructureTest {

    private static final Gson GSON = new Gson();
    private static final String NS = "israel_simulator:";
    private static final List<String> VARIANTS = List.of("government_building", "government_building_ministry");

    @Test
    @DisplayName("Start pool offers the parliament and the ministry; floor sits on the surface")
    void poolAndStructure() throws Exception {
        JsonObject pool = readJson(poolPath("government_building"));
        Set<String> locs = new LinkedHashSet<>();
        for (var el : pool.getAsJsonArray("elements")) {
            JsonObject e = el.getAsJsonObject().getAsJsonObject("element");
            assertEquals("rigid", e.get("projection").getAsString());
            locs.add(e.get("location").getAsString());
        }
        assertEquals(Set.of(NS + "government_building", NS + "government_building_ministry"), locs);
        JsonObject s = readJson("data/israel_simulator/worldgen/structure/government_building.json");
        assertEquals("israel_simulator:urban_area", s.getAsJsonArray("biomes").get(0).getAsString());
        assertEquals(-4, s.getAsJsonObject("start_height").get("absolute").getAsInt());
    }

    @Test
    @DisplayName("Both variants are detailed civic buildings with marker, menorah, flags and loot")
    void detailed() throws Exception {
        for (String v : VARIANTS) {
            Template t = Template.load(readGzip(nbtPath(v)));
            Set<String> palette = new LinkedHashSet<>();
            t.blocks.forEach(b -> palette.add(b.name));
            assertTrue(palette.size() >= 30, v + " palette too plain: " + palette.size());
            assertTrue(palette.contains("minecraft:polished_deepslate"), v + " marker");
            assertTrue(palette.contains("israel_simulator:menorah"), v + " menorah");
            assertTrue(palette.contains("minecraft:blue_wool") && palette.contains("minecraft:white_wool"), v + " flags");
            long loot = t.blocks.stream().filter(b -> b.nbt != null
                    && (NS + "chests/government_building").equals(b.nbt.get("LootTable"))).count();
            assertTrue(loot >= 2, v + " loot containers: " + loot);
            long stairs = t.blocks.stream().filter(b -> b.name.equals("minecraft:polished_deepslate_stairs")).count();
            assertTrue(stairs >= 4, v + " must have stairs to the upper floors");
        }
        Template k = Template.load(readGzip(nbtPath("government_building")));
        assertTrue(k.blocks.stream().filter(b -> b.name.equals("minecraft:quartz_pillar")).count() > 200,
                "Knesset ring of tall columns");
        assertTrue(k.blocks.stream().filter(b -> b.name.equals("minecraft:dark_oak_stairs")).count() > 30,
                "plenary seats");
        Template m = Template.load(readGzip(nbtPath("government_building_ministry")));
        assertTrue(m.blocks.stream().anyMatch(b -> b.name.equals("minecraft:yellow_concrete")), "rooftop helipad");
    }

    private JsonObject readJson(String path) throws Exception {
        InputStream in = getClass().getClassLoader().getResourceAsStream(path);
        assertNotNull(in, "Missing " + path);
        return GSON.fromJson(new InputStreamReader(in, StandardCharsets.UTF_8), JsonObject.class);
    }

    private static String poolPath(String pool) {
        return "data/israel_simulator/worldgen/template_pool/" + pool + ".json";
    }

    private static String nbtPath(String piece) {
        return "data/israel_simulator/structure/" + piece + ".nbt";
    }


    private byte[] readGzip(String path) throws Exception {
        InputStream in = getClass().getClassLoader().getResourceAsStream(path);
        assertNotNull(in, "Missing NBT: " + path);
        try (GZIPInputStream gz = new GZIPInputStream(in)) {
            return gz.readAllBytes();
        }
    }

    private record Block(String name, Map<String, Object> props, int x, int y, int z, Map<String, Object> nbt) {}

    private record Template(List<Block> blocks) {
        @SuppressWarnings("unchecked")
        static Template load(byte[] raw) throws IOException {
            DataInputStream in = new DataInputStream(new ByteArrayInputStream(raw));
            assertEquals(10, in.readByte());
            readString(in);
            Map<String, Object> root = readCompound(in);
            List<Map<String, Object>> palette = (List<Map<String, Object>>) root.get("palette");
            List<Block> out = new ArrayList<>();
            for (Map<String, Object> b : (List<Map<String, Object>>) root.get("blocks")) {
                List<Integer> pos = (List<Integer>) b.get("pos");
                Map<String, Object> state = palette.get(((Number) b.get("state")).intValue());
                Map<String, Object> props = (Map<String, Object>) state.getOrDefault("Properties", Map.of());
                out.add(new Block((String) state.get("Name"), props, pos.get(0), pos.get(1), pos.get(2),
                        (Map<String, Object>) b.get("nbt")));
            }
            return new Template(out);
        }
    }

    private static Map<String, Object> readCompound(DataInputStream in) throws IOException {
        Map<String, Object> map = new HashMap<>();
        while (true) {
            byte type = in.readByte();
            if (type == 0) {
                return map;
            }
            String name = readString(in);
            map.put(name, readPayload(in, type));
        }
    }

    private static Object readPayload(DataInputStream in, byte type) throws IOException {
        return switch (type) {
            case 1 -> in.readByte();
            case 2 -> in.readShort();
            case 3 -> in.readInt();
            case 4 -> in.readLong();
            case 5 -> in.readFloat();
            case 6 -> in.readDouble();
            case 7 -> {
                int len = in.readInt();
                in.skipBytes(len);
                yield new byte[0];
            }
            case 8 -> readString(in);
            case 9 -> readList(in);
            case 10 -> readCompound(in);
            case 11 -> {
                int len = in.readInt();
                for (int i = 0; i < len; i++) {
                    in.readInt();
                }
                yield new int[0];
            }
            case 12 -> {
                int len = in.readInt();
                for (int i = 0; i < len; i++) {
                    in.readLong();
                }
                yield new long[0];
            }
            default -> throw new IOException("Unsupported NBT type " + type);
        };
    }

    private static Object readList(DataInputStream in) throws IOException {
        byte elemType = in.readByte();
        int len = in.readInt();
        List<Object> list = new ArrayList<>(len);
        for (int i = 0; i < len; i++) {
            list.add(readPayload(in, elemType));
        }
        if (elemType == 3) {
            List<Integer> ints = new ArrayList<>(len);
            for (Object o : list) {
                ints.add(((Number) o).intValue());
            }
            return ints;
        }
        if (elemType == 10) {
            @SuppressWarnings("unchecked")
            List<Map<String, Object>> compounds = (List<Map<String, Object>>) (List<?>) list;
            return compounds;
        }
        return list;
    }

    private static String readString(DataInputStream in) throws IOException {
        int len = in.readUnsignedShort();
        return new String(in.readNBytes(len), StandardCharsets.UTF_8);
    }
}

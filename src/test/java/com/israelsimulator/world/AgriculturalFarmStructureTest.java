import static org.junit.jupiter.api.Assertions.*;

/**
 * agricultural_farm is a jigsaw moshav farmstead in the israeli_agriculture biome, generated by
 * scripts/worldgen/gen_agricultural_farm.py: farm lanes, fields, vineyard, orchards, greenhouses,
 * reservoir, sheds and a farmhouse (no more single glass box).
 */
class AgriculturalFarmStructureTest {

    private static final Gson GSON = new Gson();
    private static final String NS = "israel_simulator:";

    private static final List<String> POOLS = List.of("agricultural_farm", "farm/streets", "farm/terminators", "farm/buildings", "farm/landmarks");
    private static final List<String> STREETS = List.of("farm/lane_straight", "farm/lane_short", "farm/lane_crossroad", "farm/lane_corner", "farm/lane_t");
    /** Street pieces that are rigid (stairs, arches, gates): they carry a footing. */
    private static final Set<String> RIGID_STREETS = Set.of();
    private static final List<String> BUILDINGS = List.of("farm/wheat_field", "farm/vegetable_plots", "farm/vineyard", "farm/orchard", "farm/date_grove", "farm/polytunnel", "farm/glasshouse", "farm/reservoir", "farm/tool_shed", "farm/cowshed", "farm/chicken_coop", "farm/farmhouse");

    @Test
    @DisplayName("agricultural_farm is a beard_thin jigsaw locked to its biome, starting at farm/farmyard")
    void structureJson() throws Exception {
        JsonObject s = readJson("data/israel_simulator/worldgen/structure/agricultural_farm.json");
        assertEquals("minecraft:jigsaw", s.get("type").getAsString());
        assertEquals("beard_thin", s.get("terrain_adaptation").getAsString());
        assertTrue(s.get("size").getAsInt() >= 5, "jigsaw depth too small");
        JsonArray biomes = s.getAsJsonArray("biomes");
        assertEquals(1, biomes.size());
        assertEquals("israel_simulator:israeli_agriculture", biomes.get(0).getAsString());
        assertEquals(NS + "farm/farmyard", firstLocation("agricultural_farm"));
    }

    @Test
    @DisplayName("All pools resolve to existing pieces with the right projections")
    void poolsResolve() throws Exception {
        Set<String> all = new LinkedHashSet<>();
        for (String pool : POOLS) {
            JsonObject p = readJson(poolPath(pool));
            String fallback = p.get("fallback").getAsString();
            assertTrue(fallback.equals("minecraft:empty") || POOLS.contains(fallback.substring(NS.length())),
                    pool + " fallback must be empty or one of our pools: " + fallback);
            for (var el : p.getAsJsonArray("elements")) {
                JsonObject e = el.getAsJsonObject().getAsJsonObject("element");
                String loc = e.get("location").getAsString();
                assertTrue(loc.startsWith(NS + "farm/"), loc);
                String piece = loc.substring(NS.length());
                String proj = e.get("projection").getAsString();
                boolean street = pool.endsWith("/streets") || pool.endsWith("/terminators");
                if (street && !RIGID_STREETS.contains(piece)) {
                    assertEquals("terrain_matching", proj, loc + " streets must follow the terrain");
                } else {
                    assertEquals("rigid", proj, loc + " must be rigid");
                }
                all.add(piece);
                assertNotNull(Template.load(readGzip(nbtPath(piece))));
            }
        }
        assertTrue(all.containsAll(STREETS), "missing street pieces: " + all);
        assertTrue(all.containsAll(BUILDINGS), "missing building pieces: " + all);
    }

    @Test
    @DisplayName("Jigsaws only point at our pools; every building has one north-facing entrance on a footing")
    void jigsawWiring() throws Exception {
        List<String> pieces = new ArrayList<>(STREETS);
        pieces.add("farm/farmyard");
        for (String piece : pieces) {
            Template t = Template.load(readGzip(nbtPath(piece)));
            int streetLinks = 0;
            for (Block b : t.blocks) {
                if (!b.name.equals("minecraft:jigsaw")) continue;
                String pool = (String) b.nbt.get("pool");
                assertTrue(pool.equals("minecraft:empty") || POOLS.contains(pool.substring(NS.length())),
                        piece + " jigsaw targets unknown pool " + pool);
                if (!piece.equals("farm/farmyard") && !RIGID_STREETS.contains(piece)) {
                    assertEquals(1, b.y, piece + " jigsaws sit one above the street floor");
                }
                if ("minecraft:street".equals(b.nbt.get("name"))) streetLinks++;
            }
            assertTrue(streetLinks >= 1, piece + " must link to the street network");
        }
        for (String piece : BUILDINGS) {
            Template t = Template.load(readGzip(nbtPath(piece)));
            List<Block> jigsaws = t.blocks.stream().filter(b -> b.name.equals("minecraft:jigsaw")).toList();
            assertEquals(1, jigsaws.size(), piece + " must have exactly one entrance jigsaw");
            Block j = jigsaws.get(0);
            assertEquals("minecraft:building_entrance", j.nbt.get("name"));
            assertEquals("minecraft:empty", j.nbt.get("pool"));
            assertEquals("north_up", j.props.get("orientation"));
            assertEquals(0, j.z, piece + " entrance must be on the street-facing porch row");
            final int jx = j.x, jy = j.y;
            assertTrue(jy >= 1);
            for (int y = 0; y < jy; y++) {
                final int yy = y;
                assertTrue(t.blocks.stream().anyMatch(b -> b.x == jx && b.y == yy && b.z == 0
                                && !b.name.equals("minecraft:air")),
                        piece + " porch/footing missing under the entrance at y=" + yy);
            }
        }
    }

    @Test
    @DisplayName("Loot chests use the farm loot table, which exists")
    void lootChests() throws Exception {
        int chests = 0;
        for (String piece : BUILDINGS) {
            Template t = Template.load(readGzip(nbtPath(piece)));
            for (Block b : t.blocks) {
                if (b.nbt == null || !b.nbt.containsKey("LootTable")) continue;
                assertEquals("israel_simulator:chests/agricultural_farm", b.nbt.get("LootTable"), piece);
                assertFalse(b.nbt.containsKey("Items"), "loot must fill on open");
                if (b.name.equals("minecraft:chest")) chests++;
            }
        }
        assertTrue(chests >= 2, "expected loot chests in the shed and farmhouse, got " + chests);
        assertNotNull(getClass().getClassLoader().getResource(
                "data/israel_simulator/loot_table/chests/agricultural_farm.json"));
    }

    @Test
    @DisplayName("Plots are real farm pieces: crops on farmland next to water, varied palettes")
    void piecesAreDetailed() throws Exception {
        for (String piece : BUILDINGS) {
            Template t = Template.load(readGzip(nbtPath(piece)));
            Set<String> palette = new LinkedHashSet<>();
            long solid = t.blocks.stream().filter(b -> !b.name.equals("minecraft:air")).peek(b -> palette.add(b.name)).count();
            assertTrue(solid >= 150, piece + " too small: " + solid);
            assertTrue(palette.size() >= 9, piece + " palette too plain: " + palette);
        }
        Template start = Template.load(readGzip(nbtPath("farm/farmyard")));
        assertTrue(start.blocks.stream().anyMatch(b -> b.name.equals("minecraft:hay_block")),
                "start piece keeps the agricultural_farm marker minecraft:hay_block");
        Set<String> crops = new LinkedHashSet<>();
        for (String piece : BUILDINGS) {
            Template t = Template.load(readGzip(nbtPath(piece)));
            Map<String, String> at = new HashMap<>();
            for (Block b : t.blocks) at.put(b.x + "," + b.y + "," + b.z, b.name);
            for (Block b : t.blocks) {
                boolean crop = b.name.endsWith("_crop") || b.name.equals("israel_simulator:grapevine")
                        || List.of("minecraft:wheat", "minecraft:carrots", "minecraft:potatoes", "minecraft:beetroots").contains(b.name);
                if (!crop) continue;
                crops.add(b.name);
                assertEquals("minecraft:farmland", at.get(b.x + "," + (b.y - 1) + "," + b.z),
                        piece + " crop " + b.name + " must stand on farmland");
                boolean wet = false;
                for (int dx = -4; dx <= 4 && !wet; dx++)
                    for (int dz = -4; dz <= 4 && !wet; dz++)
                        wet = "minecraft:water".equals(at.get((b.x + dx) + "," + (b.y - 1) + "," + (b.z + dz)));
                assertTrue(wet, piece + " crop at " + b.x + "," + b.z + " has no irrigation within 4 blocks");
            }
        }
        assertTrue(crops.size() >= 8, "farm should grow many different crops: " + crops);
        Template poly = Template.load(readGzip(nbtPath("farm/polytunnel")));
        assertTrue(poly.blocks.stream().anyMatch(b -> b.name.equals("minecraft:white_stained_glass")),
                "polytunnel keeps its arched plastic shell");
    }

    private String firstLocation(String pool) throws Exception {
        return readJson(poolPath(pool)).getAsJsonArray("elements").get(0).getAsJsonObject()
                .getAsJsonObject("element").get("location").getAsString();
    }

    private static String poolPath(String pool) {
        return "data/israel_simulator/worldgen/template_pool/" + pool + ".json";
    }

    private static String nbtPath(String piece) {
        return "data/israel_simulator/structure/" + piece + ".nbt";
    }

    private JsonObject readJson(String path) throws Exception {
        InputStream in = getClass().getClassLoader().getResourceAsStream(path);
        assertNotNull(in, "Missing " + path);
        return GSON.fromJson(new InputStreamReader(in, StandardCharsets.UTF_8), JsonObject.class);
    }

    private byte[] readGzip(String path) throws Exception {
        InputStream in = getClass().getClassLoader().getResourceAsStream(path);
        assertNotNull(in, "Missing NBT: " + path);
        try (GZIPInputStream gz = new GZIPInputStream(in)) {
            return gz.readAllBytes();
        }
    }

    private record Block(String name, Map<String, Object> props, int x, int y, int z, Map<String, Object> nbt) {}

    private record Template(List<Block> blocks) {
        @SuppressWarnings("unchecked")
        static Template load(byte[] raw) throws IOException {
            DataInputStream in = new DataInputStream(new ByteArrayInputStream(raw));
            assertEquals(10, in.readByte());
            readString(in);
            Map<String, Object> root = readCompound(in);
            List<Map<String, Object>> palette = (List<Map<String, Object>>) root.get("palette");
            List<Block> out = new ArrayList<>();
            for (Map<String, Object> b : (List<Map<String, Object>>) root.get("blocks")) {
                List<Integer> pos = (List<Integer>) b.get("pos");
                Map<String, Object> state = palette.get(((Number) b.get("state")).intValue());
                Map<String, Object> props = (Map<String, Object>) state.getOrDefault("Properties", Map.of());
                out.add(new Block((String) state.get("Name"), props, pos.get(0), pos.get(1), pos.get(2),
                        (Map<String, Object>) b.get("nbt")));
            }
            return new Template(out);
        }
    }

    private static Map<String, Object> readCompound(DataInputStream in) throws IOException {
        Map<String, Object> map = new HashMap<>();
        while (true) {
            byte type = in.readByte();
            if (type == 0) {
                return map;
            }
            String name = readString(in);
            map.put(name, readPayload(in, type));
        }
    }

    private static Object readPayload(DataInputStream in, byte type) throws IOException {
        return switch (type) {
            case 1 -> in.readByte();
            case 2 -> in.readShort();
            case 3 -> in.readInt();
            case 4 -> in.readLong();
            case 5 -> in.readFloat();
            case 6 -> in.readDouble();
            case 7 -> {
                int len = in.readInt();
                in.skipBytes(len);
                yield new byte[0];
            }
            case 8 -> readString(in);
            case 9 -> readList(in);
            case 10 -> readCompound(in);
            case 11 -> {
                int len = in.readInt();
                for (int i = 0; i < len; i++) {
                    in.readInt();
                }
                yield new int[0];
            }
            case 12 -> {
                int len = in.readInt();
                for (int i = 0; i < len; i++) {
                    in.readLong();
                }
                yield new long[0];
            }
            default -> throw new IOException("Unsupported NBT type " + type);
        };
    }

    private static Object readList(DataInputStream in) throws IOException {
        byte elemType = in.readByte();
        int len = in.readInt();
        List<Object> list = new ArrayList<>(len);
        for (int i = 0; i < len; i++) {
            list.add(readPayload(in, elemType));
        }
        if (elemType == 3) {
            List<Integer> ints = new ArrayList<>(len);
            for (Object o : list) {
                ints.add(((Number) o).intValue());
            }
            return ints;
        }
        if (elemType == 10) {
            @SuppressWarnings("unchecked")
            List<Map<String, Object>> compounds = (List<Map<String, Object>>) (List<?>) list;
            return compounds;
        }
        return list;
    }

    private static String readString(DataInputStream in) throws IOException {
        int len = in.readUnsignedShort();
        return new String(in.readNBytes(len), StandardCharsets.UTF_8);
    }
}
